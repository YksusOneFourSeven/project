-- Дополнительные проверки физической модели, включая прямое редактирование SQL.
CREATE FUNCTION protect_links() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_TABLE_NAME='assignments' THEN
  IF (NEW.group_id<>OLD.group_id OR NEW.discipline_id<>OLD.discipline_id) AND EXISTS(SELECT 1 FROM assessments WHERE assignment_id=OLD.id) THEN RAISE EXCEPTION 'Назначение содержит работы' USING ERRCODE='23514'; END IF;
 ELSIF TG_TABLE_NAME='assessments' THEN
  IF (NEW.assignment_id<>OLD.assignment_id OR NEW.grading<>OLD.grading) AND EXISTS(SELECT 1 FROM grades WHERE assessment_id=OLD.id) THEN RAISE EXCEPTION 'Работа содержит оценки' USING ERRCODE='23514'; END IF;
 ELSIF TG_TABLE_NAME='disciplines' THEN
  IF NEW.control_form<>OLD.control_form AND EXISTS(SELECT 1 FROM assignments WHERE discipline_id=OLD.id) THEN RAISE EXCEPTION 'Дисциплина назначена' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER assignments_history BEFORE UPDATE ON assignments FOR EACH ROW EXECUTE FUNCTION protect_links();
CREATE TRIGGER assessments_history BEFORE UPDATE ON assessments FOR EACH ROW EXECUTE FUNCTION protect_links();
CREATE TRIGGER disciplines_history BEFORE UPDATE ON disciplines FOR EACH ROW EXECUTE FUNCTION protect_links();
CREATE FUNCTION check_scale() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE form text;
BEGIN
 SELECT d.control_form INTO form FROM assignments a JOIN disciplines d ON d.id=a.discipline_id WHERE a.id=NEW.assignment_id;
 IF (NEW.grading='зачет') IS DISTINCT FROM (form='зачет') THEN RAISE EXCEPTION 'Несовместимая шкала' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER assessments_scale BEFORE INSERT OR UPDATE ON assessments FOR EACH ROW EXECUTE FUNCTION check_scale();
